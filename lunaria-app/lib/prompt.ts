// light_probe テンプレート（つむぎ音声で映えるテンポ感）
const PROBE_LIGHT = [
  'なに、どうしたの？',
  'え、なにかあった？',
  'それ、ちょっと気になる',
  'どうしたん、それ',
  'それってどんな感じ？',
]
const PROBE_DEEP = [
  'それ、大丈夫？',
  'ちゃんと聞くよ',
  'それ結構しんどそうだね',
  'もう少し詳しく聞いていい？',
  'なんか、いろいろ重なってる感じ？',
]

export function getProbeTemplate(
  windowScore: number,
  usedRecently: string[],
): string {
  const pool = windowScore >= 6 ? PROBE_DEEP : PROBE_LIGHT
  const available = pool.filter(t => !usedRecently.includes(t))
  const target = available.length > 0 ? available : pool
  return target[Math.floor(Math.random() * target.length)]
}

