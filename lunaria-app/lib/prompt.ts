// light_probe テンプレート
const PROBE_LIGHT = [
  'なに、どうしたの？', 'え、なにかあった？',
  'それ、ちょっと気になる', 'どうしたん、それ',
]
const PROBE_DEEP = [
  'それ、大丈夫？', 'ちゃんと聞くよ',
  'それ結構しんどそう', 'もう少し聞いていい？',
]

export function getProbeTemplate(windowScore: number): string {
  const pool = windowScore >= 6 ? PROBE_DEEP : PROBE_LIGHT
  return pool[Math.floor(Math.random() * pool.length)]
}

