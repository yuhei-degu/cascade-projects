// 全 migration を 1 ファイルに結合する(新規 Supabase プロジェクトへの復旧用)
// 使い方: npm run sql:pack-all → supabase/full-schema.sql を Supabase SQL Editor に貼る
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { join } from 'node:path'

const DIR = 'supabase/migrations'
const files = readdirSync(DIR).filter(f => f.endsWith('.sql')).sort()
if (!files.length) { console.error('no migrations found'); process.exit(1) }

const nums = files.map(f => parseInt(f.slice(0, 3), 10))
const missing = []
for (let i = 1; i <= nums[nums.length - 1]; i++) if (!nums.includes(i)) missing.push(i)

let out = '-- Lunaria full schema (auto-generated by scripts/sql-pack-all.mjs)\n'
out += '-- generated: ' + new Date().toISOString() + '\n'
out += '-- migrations: ' + files.length + ' (' + files[0] + ' .. ' + files[files.length - 1] + ')\n'
out += '-- missing numbers: ' + (missing.length ? missing.join(',') : 'none') + '\n'
out += '-- 新規プロジェクトに貼る場合は上から順に全実行すること\n\n'

for (const f of files) {
  const body = readFileSync(join(DIR, f), 'utf8').replace(/\r\n/g, '\n').trim()
  out += '\n-- ==========================================================\n'
  out += '-- ' + f + '\n'
  out += '-- ==========================================================\n'
  out += body + '\n'
}

writeFileSync('supabase/full-schema.sql', out, 'utf8')
console.log('wrote supabase/full-schema.sql')
console.log('  migrations: ' + files.length)
console.log('  missing: ' + (missing.length ? missing.join(',') : 'none'))
console.log('  size: ' + Math.round(out.length / 1024) + ' KB')
