// 大量ケース定義 — 製品ゲート用「正常終了」テストの入力データ
// 判定基準は eval-mass.mts 側(機械判定)。品質の絶対値は eval-luna 系(LLM審査)が担当。
// ここでの「正常終了」= 事故がないこと:
//   空返答/思考漏れ/NG語/敬語化/一人称事故/英語化/暴走長文/質問過多/ケース固有の禁止語

export interface Turn { role: 'user' | 'assistant'; content: string }

export interface MassCase {
  id: string
  category: string
  turns: string[]
  seed?: Turn[]
  /** 最終返答に最低1つ含まれるべき語 */
  expectAny?: string[]
  /** どの返答にも含まれてはいけない語 */
  forbid?: string[]
  /** 文数上限(デフォルト6。テンポでなく暴走検出) */
  maxSentences?: number
  /** 質問記号上限(デフォルト2) */
  maxQuestions?: number
  /** 長文許容(深刻系) */
  allowLong?: boolean
}

let seq = 0
function make(category: string, defaults: Partial<MassCase>, inputs: Array<string | string[] | Partial<MassCase> & { t: string | string[] }>): MassCase[] {
  return inputs.map(input => {
    seq++
    const extra: Partial<MassCase> & { t?: string | string[] } =
      typeof input === 'string' || Array.isArray(input) ? {} : input
    const t = typeof input === 'string' ? [input]
      : Array.isArray(input) ? input
      : Array.isArray(extra.t) ? extra.t : [extra.t as string]
    const { t: _ignored, ...rest } = extra
    return {
      id: `${category}-${String(seq).padStart(3, '0')}`,
      category,
      turns: t,
      ...defaults,
      ...rest,
    } as MassCase
  })
}

