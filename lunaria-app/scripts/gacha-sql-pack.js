#!/usr/bin/env node

const fs = require('fs')
const path = require('path')

const MIGRATIONS = [
  '014_gacha_content_v2.sql',
  '015_gacha_pity_system.sql',
  '016_gacha_pity_threshold.sql',
  '017_diary_v1_schema.sql',
  '018_core_memory_provenance.sql',
]

const ROOT = path.resolve(__dirname, '..')
const MIGRATION_DIR = path.join(ROOT, 'supabase', 'migrations')
const OUT_DIR = path.join(ROOT, 'supabase', 'manual')
const OUT_FILE = path.join(OUT_DIR, '014_018_lunaria_apply_bundle.sql')

function readMigration(name) {
  const filePath = path.join(MIGRATION_DIR, name)
  if (!fs.existsSync(filePath)) throw new Error(`Missing migration: ${filePath}`)
  return fs.readFileSync(filePath, 'utf8').trim()
}

function buildVerificationSql() {
  return `
-- ============================================================================
-- Post-apply verification queries
-- ============================================================================

-- 1. Active pool should be 41 total with this rarity shape.
select rarity, count(*) as items
  from public.lunaria_gacha_pool
 where is_active
 group by rarity
 order by rarity;

-- Expected:
-- common_a      8
-- common_b      7
-- rare_a        3
-- rare_b        3
-- epic          3
-- legendary     2
-- urban_legend 15

-- 2. Pity history audit columns should exist.
select column_name
  from information_schema.columns
 where table_schema = 'public'
   and table_name = 'lunaria_gacha_history'
   and column_name in ('pity_before', 'pity_after', 'pity_triggered')
 order by column_name;

-- 3. draw_gacha_v2 should exist and keep a locked search_path.
select proname, proconfig
  from pg_proc p
  join pg_namespace n on p.pronamespace = n.oid
 where n.nspname = 'public'
   and proname = 'draw_gacha_v2';

-- 4. 016 should have replaced the RPC threshold with 200-draw logic.
select
  pg_get_functiondef('public.draw_gacha_v2(uuid, uuid, text)'::regprocedure) like '%>= 199%' as has_200_draw_threshold,
  pg_get_functiondef('public.draw_gacha_v2(uuid, uuid, text)'::regprocedure) like '%>= 99%' as still_has_100_draw_threshold;

-- Expected:
-- has_200_draw_threshold = true
-- still_has_100_draw_threshold = false

-- 5. Only service_role should execute draw_gacha_v2.
select grantee, privilege_type
  from information_schema.routine_privileges
 where routine_schema = 'public'
   and routine_name = 'draw_gacha_v2'
 order by grantee;

-- 6. Diary v1 columns from 017 should exist.
select column_name
  from information_schema.columns
 where table_schema = 'public'
   and table_name = 'lunaria_diary_logs'
   and column_name in (
     'title',
     'talked_about',
     'memory_changes',
     'source_message_count',
     'generated_at'
   )
 order by column_name;

-- 7. Core memory provenance columns from 018 should exist.
select column_name
  from information_schema.columns
 where table_schema = 'public'
   and table_name = 'lunaria_core_memory'
   and column_name in (
     'source_date',
     'source_message_id',
     'confidence',
     'status',
     'last_confirmed_at',
     'created_by',
     'notes'
   )
 order by column_name;

-- 8. Core memory constraints from 018 should exist and be valid.
select conname, convalidated
  from pg_constraint
 where conname in (
   'lunaria_core_memory_confidence_range',
   'lunaria_core_memory_status_check',
   'lunaria_core_memory_created_by_check'
 )
 order by conname;
`.trim()
}

function buildBundle() {
  const sections = MIGRATIONS.map(name => {
    return [
      '-- ============================================================================',
      `-- ${name}`,
      '-- ============================================================================',
      readMigration(name),
      '',
    ].join('\n')
  })

  return [
    '-- Lunaria manual apply bundle: 014 -> 015 -> 016 -> 017 -> 018',
    '-- Generated by: npm run gacha:sql-pack',
    '-- Paste into Supabase SQL Editor only after confirming the target project.',
    '-- This file is generated for manual application convenience; source of truth remains supabase/migrations/*.sql.',
    '',
    ...sections,
    buildVerificationSql(),
    '',
  ].join('\n')
}

function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true })
  fs.writeFileSync(OUT_FILE, buildBundle(), 'utf8')
  console.log(`Wrote ${path.relative(ROOT, OUT_FILE)}`)
  console.log('Apply order: 014 -> 015 -> 016 -> 017 -> 018')
  console.log('After applying, run: npm run supabase:verify http://localhost:3000')
}

main()

