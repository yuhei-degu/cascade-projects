#!/usr/bin/env node

const fs = require('fs')
const path = require('path')

const MIGRATIONS = [
  '020_user_items.sql',
  '021_character_states.sql',
]

const ROOT = path.resolve(__dirname, '..')
const MIGRATION_DIR = path.join(ROOT, 'supabase', 'migrations')
const OUT_DIR = path.join(ROOT, 'supabase', 'manual')
const OUT_FILE = path.join(OUT_DIR, '020_021_character_items_apply_bundle.sql')

function readMigration(name) {
  const filePath = path.join(MIGRATION_DIR, name)
  if (!fs.existsSync(filePath)) throw new Error(`Missing migration: ${filePath}`)
  return fs.readFileSync(filePath, 'utf8').trim()
}

function verificationSql() {
  return `
-- ============================================================================
-- Post-apply verification queries for 020/021
-- ============================================================================

-- 1. New tables should exist.
select table_name
  from information_schema.tables
 where table_schema = 'public'
   and table_name in ('lunaria_user_items', 'lunaria_character_states')
 order by table_name;

-- 2. RLS should be enabled.
select relname, relrowsecurity
  from pg_class
 where relname in ('lunaria_user_items', 'lunaria_character_states')
 order by relname;

-- 3. User items should expose expected columns.
select column_name
  from information_schema.columns
 where table_schema = 'public'
   and table_name = 'lunaria_user_items'
   and column_name in (
     'user_id', 'pool_id', 'obtained_from', 'obtained_at',
     'is_equipped', 'duplicate_count', 'last_obtained_at', 'metadata', 'deleted_at'
   )
 order by column_name;

-- 4. Character states should expose expected columns.
select column_name
  from information_schema.columns
 where table_schema = 'public'
   and table_name = 'lunaria_character_states'
   and column_name in (
     'user_id', 'character_profile_id', 'current_outfit_pool_id',
     'current_background_pool_id', 'current_expression', 'current_motion',
     'affinity_level', 'unlocked_expressions', 'unlocked_motions', 'metadata', 'deleted_at'
   )
 order by column_name;

-- 5. Backfill sanity check.
select
  (select count(*) from public.lunaria_gacha_inventory) as old_inventory_rows,
  (select count(*) from public.lunaria_user_items) as user_item_rows,
  (select count(*) from public.lunaria_character_states) as character_state_rows;

-- 6. Policy names should exist.
select tablename, policyname, cmd
  from pg_policies
 where schemaname = 'public'
   and tablename in ('lunaria_user_items', 'lunaria_character_states')
 order by tablename, policyname;
`.trim()
}

function buildBundle() {
  const sections = MIGRATIONS.map(name => [
    '-- ============================================================================',
    `-- ${name}`,
    '-- ============================================================================',
    readMigration(name),
    '',
  ].join('\n'))

  return [
    '-- Lunaria manual apply bundle: 020 -> 021',
    '-- Generated by: npm run character:sql-pack',
    '-- Paste into Supabase SQL Editor only after confirming the target project.',
    '-- Source of truth remains supabase/migrations/*.sql.',
    '',
    ...sections,
    verificationSql(),
    '',
  ].join('\n')
}

function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true })
  const bundle = buildBundle()
  fs.writeFileSync(OUT_FILE, bundle, 'utf8')
  console.log(`Wrote ${path.relative(ROOT, OUT_FILE)}`)
}

main()
